import { lunesDe, sumarDias } from './fechas';

const LUNES = lunesDe(new Date());

function fecha(dia: number, hora: string): string {
  const [horas, minutos] = hora.split(':').map(Number);
  const resultado = sumarDias(LUNES, dia);
  resultado.setHours(horas, minutos);
  return resultado.toISOString();
}

